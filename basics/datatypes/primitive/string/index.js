// ===============================
// JavaScript String Data Type
// Code Examples
// ===============================

// 1️⃣ Double Quotes
let a = "Hello";
console.log(a);
console.log(typeof a);

// 2️⃣ Single Quotes
let b = 'Hello';
console.log(b);
console.log(typeof b);

// 3️⃣ Backticks
let c = `Hello`;
console.log(c);
console.log(typeof c);

// 4️⃣ Empty String
let d = "";
console.log(d);
console.log(typeof d);

// 5️⃣ Number Inside Quotes
let e = "100";
console.log(e);
console.log(typeof e);

// 6️⃣ Boolean Word Inside Quotes
let f = "true";
console.log(f);
console.log(typeof f);

// 7️⃣ String Object
let g = new String("Hello");
console.log(g);
console.log(typeof g);
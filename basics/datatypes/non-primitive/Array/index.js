// ===============================
// JavaScript Array Data Type
// Full Code Examples
// ===============================


// ---------------------------------
// 1️⃣ Basic Array
// ---------------------------------

let a = [10, 20, 30, 40];

console.log(a);
// Output: [10, 20, 30, 40]

console.log(typeof a);
// Output: object

// Explanation:
// Array is a special type of object



// ---------------------------------
// 2️⃣ Access Values by Index
// ---------------------------------

console.log(a[0]);     // 10
console.log(a[1]);     // 20
console.log(a[3]);     // 40

// Index starts from 0



// ---------------------------------
// 3️⃣ Update Value
// ---------------------------------

a[1] = 200;

console.log(a);
// [10, 200, 30, 40]



// ---------------------------------
// 4️⃣ Add Value at End
// ---------------------------------

a.push(50);

console.log(a);
// [10, 200, 30, 40, 50]



// ---------------------------------
// 5️⃣ Remove Last Value
// ---------------------------------

a.pop();

console.log(a);
// [10, 200, 30, 40]



// ---------------------------------
// 6️⃣ Add Value at Start
// ---------------------------------

a.unshift(5);

console.log(a);
// [5, 10, 200, 30, 40]



// ---------------------------------
// 7️⃣ Remove First Value
// ---------------------------------

a.shift();

console.log(a);
// [10, 200, 30, 40]



// ---------------------------------
// 8️⃣ Array Length
// ---------------------------------

console.log(a.length);   // 4



// ---------------------------------
// 9️⃣ Mixed Data Types
// ---------------------------------

let b = [100, "Hello", true, null];

console.log(b);



// ---------------------------------
// 🔟 Nested Array
// ---------------------------------

let c = [
    [1, 2],
    [3, 4]
];

console.log(c[0][1]);   // 2
console.log(c[1][0]);   // 3



// ---------------------------------
// 1️⃣1️⃣ for Loop
// ---------------------------------

for (let i = 0; i < a.length; i++) {
    console.log(a[i]);
}



// ---------------------------------
// 1️⃣2️⃣ for...of Loop
// ---------------------------------

for (let value of a) {
    console.log(value);
}



// ---------------------------------
// 1️⃣3️⃣ indexOf()
// ---------------------------------

console.log(a.indexOf(30));   // index position
console.log(a.indexOf(500));  // -1



// ---------------------------------
// 1️⃣4️⃣ includes()
// ---------------------------------

console.log(a.includes(200)); // true
console.log(a.includes(999)); // false



// ---------------------------------
// 1️⃣5️⃣ join()
// ---------------------------------

console.log(a.join("-"));

// Example:
// 10-200-30-40



// ---------------------------------
// 1️⃣6️⃣ slice()
// ---------------------------------

console.log(a.slice(1, 3));

// Output:
// [200, 30]



// ---------------------------------
// 1️⃣7️⃣ splice()
// ---------------------------------

a.splice(1, 1);

console.log(a);

// Removed one item from index 1



// ---------------------------------
// 1️⃣8️⃣ Reverse
// ---------------------------------

a.reverse();

console.log(a);



// ---------------------------------
// 1️⃣9️⃣ Sort
// ---------------------------------

let d = [5, 2, 8, 1];

d.sort();

console.log(d);



// ---------------------------------
// 2️⃣0️⃣ Real Life Example
// ---------------------------------

let students = ["Ram", "Sam", "John"];

console.log(students[1]);   // Sam



// ---------------------------------
// 2️⃣1️⃣ Best Practice
// ---------------------------------

if (Array.isArray(a)) {
    console.log("This is array");
}
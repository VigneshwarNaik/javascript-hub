// ===============================
// JavaScript Number Data Type
// ===============================

// 1️⃣ Integer Number
let a = 100;
console.log(a);          
console.log(typeof a);   


// 2️⃣ Decimal Number
let b = 100.5;
console.log(b);
console.log(typeof b);


// 3️⃣ Positive Infinity
let c = 1 / 0;
console.log(c);
console.log(typeof c);


// 4️⃣ Negative Infinity
let d = -1 / 0;
console.log(d);
console.log(typeof d);


// 5️⃣ NaN (Not a Number)
let e = "Hello" / 123;
console.log(e);
console.log(typeof e);